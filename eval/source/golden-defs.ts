import type { DocDef } from "../../scripts/docgen/types";

const two = (n: number) => (Math.round(n * 100) / 100).toFixed(2);

/**
 * Fill in computed values so the documents are arithmetically consistent:
 *   row cell "="            -> quantity x unit_price - discount
 *   fields.subtotal "="     -> sum of line amounts
 *   fields.tax_total "=8%"  -> that rate applied to (subtotal - discount_total)
 *   fields.total "="        -> subtotal - discount + tax + shipping + tip
 *   BOL totals "="          -> column sums
 */
function finalize(def: DocDef): DocDef {
  const idx = (key: string) => def.columns.findIndex((c) => c.key === key);
  const q = idx("quantity");
  const p = idx("unit_price");
  const a = idx("amount");
  const d = idx("discount");
  const rows = def.rows.map((row) => {
    if (a >= 0 && row[a] === "=") {
      const next = row.slice();
      next[a] = two(Number(row[q]) * Number(row[p]) - (d >= 0 && row[d] ? Number(row[d]) : 0));
      return next;
    }
    return row;
  });
  const fields = { ...def.fields };
  const num = (key: string) => (fields[key] && fields[key] !== "=" ? Number(fields[key]) : 0);
  const sum = (key: string) => rows.reduce((n, row) => n + (Number(row[idx(key)]) || 0), 0);

  if (fields.subtotal === "=") fields.subtotal = two(sum("amount"));
  if (fields.tax_total?.startsWith("=")) {
    const rate = Number(fields.tax_total.slice(1).replace("%", "")) / 100;
    fields.tax_total = two((num("subtotal") - num("discount_total")) * rate);
  }
  if (fields.total === "=") {
    const base = fields.subtotal !== undefined ? num("subtotal") : sum("amount");
    fields.total = two(base - num("discount_total") + num("tax_total") + num("shipping_total") + num("tip"));
  }
  if (fields.amount_due === "=") fields.amount_due = fields.total;
  if (fields.total_packages === "=") fields.total_packages = String(sum("package_qty"));
  if (fields.total_handling_units === "=") fields.total_handling_units = String(sum("handling_unit_qty"));
  if (fields.total_weight === "=") fields.total_weight = `${sum("weight")} lb`;
  return { ...def, rows, fields };
}

